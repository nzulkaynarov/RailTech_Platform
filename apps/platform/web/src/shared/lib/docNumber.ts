/**
 * Бизнес-номера объектов (SPEC-v3 §2.2). Во внешних адресах и ссылках — только они, внутренних идентификаторов
 * бэкендов в интерфейсе нет. Номер непрозрачен: обозначение и формат задаёт владелец («Настройки · Нумерация»),
 * поэтому по префиксу вид объекта не определяется, а «похоже на номер» — одна общая проверка.
 */

/** Без пробелов, с цифрой, до 64 знаков; совпадает с `DOC_NUMBER_RE` BFF. Вид, год и разделители решает бэкенд. */
const LOOKS_LIKE_NUMBER = /^(?=\S*\d)\S{2,64}$/;

/** «Похоже на номер документа»: адрес `/eds/inbox/IN-104/26` с незакодированной «/» — одна карточка. */
export function isDocNumber(text: string): boolean {
  return LOOKS_LIKE_NUMBER.test(text.trim());
}

/** Часть адреса для номера: `PRJ-2026-104/26` → `PRJ-2026-104%2F26` (BFF принимает бизнес-номер). */
export function docNumberToPath(number: string): string {
  return encodeURIComponent(number);
}
