"""Номер документа в адресе: ищется как есть, префикс не разбирается.

Обозначения видов задаёт владелец («Настройки · Нумерация», решение 2026-11-13): по умолчанию
латиницей (`IN-019/26`, `OUT-005/26`, `MEMO-2026/001`, `RFQ-1126-01`); выданные раньше номера
перенумерованы (СЦ-5), поиск по прежнему номеру делает бэкенд. Шаблон с конкретным префиксом
ломался на каждом новом обозначении (прогон СЦ-2, 2026-11-19: директор не мог открыть
`IN-001/26`), поэтому здесь — только «похоже на номер», а совпадение решает реестр EDS точным
сравнением.
"""

import re

#: Без пробелов, с цифрой, до 64 знаков — вид, год и разделители решает реестр.
DOC_NUMBER_RE = re.compile(r"^(?=[^\s]*\d)[^\s]{2,64}$")
