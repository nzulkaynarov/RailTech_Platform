import { describe, expect, it } from "vitest";

import { rangePresets } from "./datePresets";

const days = (now: string) =>
  Object.fromEntries(
    rangePresets(now).map((p) => [
      p.label,
      `${p.value[0].format("YYYY-MM-DD")}..${p.value[1].format("YYYY-MM-DD")}`,
    ]),
  );

describe("rangePresets", () => {
  it.each([
    // 12 окт 2026, 10:00 по Ташкенту
    [
      "2026-10-12T05:00:00Z",
      {
        Сегодня: "2026-10-12..2026-10-12",
        Вчера: "2026-10-11..2026-10-11",
        "7 дней": "2026-10-06..2026-10-12",
        "30 дней": "2026-09-13..2026-10-12",
        "Этот месяц": "2026-10-01..2026-10-12",
        "Прошлый месяц": "2026-09-01..2026-09-30",
      },
    ],
    // 1 марта, 02:00 по Ташкенту, а в UTC ещё 28 февраля — день считается по Ташкенту
    [
      "2026-02-28T21:00:00Z",
      {
        Сегодня: "2026-03-01..2026-03-01",
        Вчера: "2026-02-28..2026-02-28",
        "7 дней": "2026-02-23..2026-03-01",
        "30 дней": "2026-01-31..2026-03-01",
        "Этот месяц": "2026-03-01..2026-03-01",
        "Прошлый месяц": "2026-02-01..2026-02-28",
      },
    ],
    // январь → прошлый месяц в прошлом году
    [
      "2027-01-15T07:00:00Z",
      {
        Сегодня: "2027-01-15..2027-01-15",
        Вчера: "2027-01-14..2027-01-14",
        "7 дней": "2027-01-09..2027-01-15",
        "30 дней": "2026-12-17..2027-01-15",
        "Этот месяц": "2027-01-01..2027-01-15",
        "Прошлый месяц": "2026-12-01..2026-12-31",
      },
    ],
  ])("at %s", (now, expected) => {
    expect(days(now)).toEqual(expected);
  });

  it("keeps the order shown in the picker", () => {
    expect(rangePresets("2026-10-12T05:00:00Z").map((p) => p.label)).toEqual([
      "Сегодня",
      "Вчера",
      "7 дней",
      "30 дней",
      "Этот месяц",
      "Прошлый месяц",
    ]);
  });
});
