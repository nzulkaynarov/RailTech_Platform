/**
 * С какой ширины сайдбар стартует РАЗВЁРНУТЫМ.
 *
 * Проход глазами 03-08 нашёл «планшетный провал»: `useIsMobile` считает мобильным только
 * `≤767px`, поэтому на 768–1279px сайдбар оставался открытым на 256px и резал контент ровно
 * на свою ширину — у реестра сделок за экран уходили «Сумма», «Ответственный», «Дата» и
 * колонка действий. Мобильная ширина была в порядке (там сайдбар уходит в оверлей), десктоп
 * тоже — проваливалась только середина.
 *
 * Эталон: Odoo, Linear и Notion на планшете держат навигацию СВЁРНУТОЙ В ИКОНКИ — это не
 * оверлей (он закрывает контент) и не полная панель (она его вытесняет). У нас режим уже есть
 * (`collapsible="icon"`), не хватало только стартового состояния.
 *
 * Читаем `matchMedia` СИНХРОННО при первом рендере: `defaultOpen` попадает в `useState`
 * инициализатором и позже не перечитывается, поэтому реактивный хук (он возвращает `false` до
 * эффекта) здесь дал бы всегда «развёрнуто». Дальше состояние принадлежит пользователю —
 * ручное переключение и запоминание работают как раньше.
 */
export const TABLET_QUERY = '(min-width: 768px) and (max-width: 1279px)';

export function sidebarDefaultOpen(): boolean {
  if (typeof window === 'undefined' || typeof window.matchMedia !== 'function') return true;
  return !window.matchMedia(TABLET_QUERY).matches;
}
