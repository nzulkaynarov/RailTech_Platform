def seed_countries(apps=None, schema_editor=None):
    if apps is None:
        from django.apps import apps as django_apps

        apps = django_apps

    try:
        Country = apps.get_model("core", "Country")
    except LookupError:
        Country = apps.get_model("master_data", "Country")

    for alpha2, alpha3, numeric, name, sort_order in ISO_COUNTRIES:
        country, created = Country.objects.get_or_create(
            code=alpha2,
            defaults={
                "name": name,
                "alpha2": alpha2,
                "alpha3": alpha3,
                "iso_numeric": numeric,
                "sort_order": sort_order,
                "is_active": True,
                "vat_rate": CURATED_VAT.get(alpha2),
            },
        )
        if created:
            continue
        updates = {}
        if not country.alpha2:
            updates["alpha2"] = alpha2
        if not country.alpha3:
            updates["alpha3"] = alpha3
        if not country.iso_numeric:
            updates["iso_numeric"] = numeric
        if not country.sort_order:
            updates["sort_order"] = sort_order
        if updates:
            for field, value in updates.items():
                setattr(country, field, value)
            country.save(update_fields=list(updates))
