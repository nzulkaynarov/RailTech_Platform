"""Записка о звонке (СЦ-6): одностраничный PDF «Кто звонил / Что просил» как файл сотрудника.

Заявка по звонку не имеет файла-основания, поэтому записку делает система: EDS строит тело `rt_docs`, рендерит его в
воркере (очередь `renders`, правило B-094 — синхронного рендера в API нет), макет `internal`, итоговый (без «ПРОЕКТ»), и
сохраняет PDF как `StoredFile` вызывающего сотрудника — тот самый файл, который `files.attach` принимает при
регистрации письма по заявке.

Идемпотентность — по `(request_key, сотрудник)`: `id` файла = `uuid5`, повтор с тем же ключом отдаёт тот же файл, а
не новый (первое содержимое остаётся). Ввод рендера несёт `call_note.file_id` — поэтому хеш рендера уникален для файла
и связь «рендер → файл» находится по нему без новых таблиц; файл появляется в той же транзакции, что и итог рендера.
"""

