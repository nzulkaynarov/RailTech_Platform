def note_id(request_key: str, crm_user_id: int) -> uuid.UUID:
    """Идентификатор файла записки: один на `(request_key, сотрудник)`."""
    return uuid.uuid5(NAMESPACE, f"{crm_user_id}:{request_key}")


def _text(value: str, *, bold: bool = False) -> dict[str, Any]:
    node: dict[str, Any] = {"type": "text", "text": value}
    if bold:
        node["marks"] = [{"type": "bold"}]
    return node


def _para(value: str, *, bold: bool = False, note: bool = False) -> dict[str, Any]:
    node: dict[str, Any] = {"type": "paragraph", "content": [_text(value, bold=bold)]}
    if note:
        node["attrs"] = {"variant": "note"}
    return node


def _row(label: str, value: str) -> dict[str, Any]:
    cells = [
        {"type": "tableCell", "content": [_para(label, bold=True)]},
        {"type": "tableCell", "content": [_para(value)]},
    ]
    return {"type": "tableRow", "content": cells}


def is_call(data: CallNoteIn) -> bool:
    """Звонок (или без канала) — «Записка о звонке»; любой другой канал — «Записка о запросе», то же тело."""
    return not data.channel or data.channel == "phone"


def build_body(data: CallNoteIn, taken_by: str) -> dict[str, Any]:
    """Тело записки: заголовок, реквизиты, «Что просил», исходное сообщение, вложения, примечание системы."""
    text = TEXT[data.lang]
    call = is_call(data)
    when = data.called_at.astimezone(clock.COMPANY_TZ).strftime("%d.%m.%Y %H:%M")
    pairs = [
        (text["caller" if call else "client"], data.caller_name),
        (text["company"], data.company),
        (text["phone"], data.phone),
        (text["email"], data.email),
        (text["when"], when),
        (text["taken_by"], taken_by),
        (text["lead"], data.lead),
        (text["channel"], None if call else text.get(f"channel_{data.channel}", data.channel)),
    ]
    rows = [_row(label, value.strip()) for label, value in pairs if value and value.strip()]
    content: list[dict[str, Any]] = [
        {"type": "heading", "attrs": {"level": 1}, "content": [_text(text["title" if call else "request_title"])]},
        {"type": "table", "attrs": {"columnWidths": [30, 70], "variant": "plain"}, "content": rows},
    ]
    need = [line.strip() for line in (data.need or "").splitlines() if line.strip()]
    if need:
        content.append(_para(text["need"], bold=True))
        content.extend(_para(line) for line in need)
    message = [line.strip() for line in (data.message or "").splitlines() if line.strip()]
    if message:
        content.append(_para(text["message"], bold=True))
        content.extend(_para(line) for line in message)
    if data.attachments:
        content.append(_para(text["attachments"], bold=True))
        content.extend(_para(name) for name in data.attachments)
    footnote = text["by_lead"] + data.lead.strip() if data.lead and data.lead.strip() else text["by_call"]
    content.append(_para(footnote, note=True))
    body = {"version": 1, "lang": data.lang, "doc": {"type": "doc", "content": content}}
    try:
        normalized = normalize_body(body)
        validate_body(normalized)
    except BodyError as exc:
        raise invalid_fields("Записку о звонке не собрать из этих данных.", body=str(exc)[:300]) from None
    return normalized


def file_name(data: CallNoteIn) -> str:
    """«Записка о звонке L-0001.pdf»; без лида — по дате звонка."""
    suffix = (
        data.lead.strip() if data.lead and data.lead.strip() else data.called_at.astimezone(clock.COMPANY_TZ).date()
    )
    title = TEXT[data.lang]["title" if is_call(data) else "request_title"]
    return files.clean_name(f"{title} {suffix}.pdf")


async def _payload(
    session: AsyncSession, employee: Employee, data: CallNoteIn, file_id: uuid.UUID
) -> tuple[dict[str, Any], str | None]:
    head = await letterhead.current(session)
    if head is None:
        raise conflict("letterhead_missing", renders.LETTERHEAD_MISSING)
    taken_by = (data.taken_by or "").strip() or employee.full_name
    payload: dict[str, Any] = {
        "renderer": renders.RENDERER_VERSION,
        "layout": LAYOUT,
        "body": build_body(data, taken_by),
        "meta": {
            "number": None,
            "date": None,
            "addressee": [],
            "reply_to": None,
            "executor": None,
            "basis_text": None,
            "verification_code": None,
            "verification_url": None,
        },
        "letterhead": {
            "company_name": letterhead.text(head, "company_name", data.lang),
            "requisites": letterhead.requisites(head, data.lang),
            "footer": letterhead.footer(head, data.lang),
            "accent": head.accent_color or renders.DEFAULT_ACCENT,
            "font": head.font_family,
        },
        "logo_sha256": head.logo_sha256,
        "call_note": {"file_id": str(file_id), "owner": employee.crm_user_id, "name": file_name(data)},
    }
    return payload, head.logo_sha256


async def _ref(session: AsyncSession, file_id: uuid.UUID) -> Any:
    version = await files.get_version(session, file_id, None)
    return files.to_ref(version, await load_directory(session, [version.uploaded_by]))


async def _materialize(session: AsyncSession, storage: ObjectStorage, render: DocumentRender) -> None:
    """Готовый PDF → файл сотрудника (`StoredFile` + версия 1); повтор ничего не меняет.

    Вызывается под блокировкой строки рендера, поэтому два вызова не создают файл дважды."""
    meta = render.payload["call_note"]
    file_id = uuid.UUID(meta["file_id"])
    if await session.get(StoredFile, file_id) is not None:
        return
    data = b"".join([chunk async for chunk in renders.stream(storage, render)])
    now = clock.now()
    session.add(StoredFile(id=file_id, created_by=int(meta["owner"]), created_at=now))
    await session.flush()
    key = f"files/{file_id}/v1"
    session.add(
        FileVersion(
            file_id=file_id,
            version=1,
            name=str(meta["name"]),
            content_type=CONTENT_TYPE,
            size=len(data),
            sha256=files.digest(data),
            s3_key=key,
            uploaded_by=int(meta["owner"]),
            uploaded_at=now,
        )
    )
    await session.flush()
    await storage.put(key, data, CONTENT_TYPE)


def on_render_finished(storage: ObjectStorage) -> Callable[[AsyncSession, DocumentRender], Awaitable[None]]:
    """Обработчик итога рендера (`renders.run`): готовая записка становится файлом сотрудника."""

    async def handle(session: AsyncSession, render: DocumentRender) -> None:
        if render.status == "ready" and "call_note" in render.payload:
            await _materialize(session, storage, render)

    return handle


async def request(session: AsyncSession, storage: ObjectStorage, employee: Employee, data: CallNoteIn) -> CallNote:
    """Заказать записку: файл уже есть — он же, иначе рендер идёт в очередь (после коммита, `take_pending`)."""
    file_id = note_id(data.request_key, employee.crm_user_id)
    if await session.get(StoredFile, file_id) is not None:
        return CallNote(id=file_id, status="ready", error=None, file=await _ref(session, file_id))
    payload, logo_sha = await _payload(session, employee, data, file_id)
    render_hash = renders.digest(payload)
    now = clock.now()
    await session.execute(
        insert(DocumentRender)
        .values(
            hash=render_hash,
            status="pending",
            final=True,
            payload=payload,
            logo_sha256=logo_sha,
            attempts=0,
            created_at=now,
        )
        .on_conflict_do_nothing(index_elements=["hash"])
    )
    row = (
        await session.execute(select(DocumentRender).where(DocumentRender.hash == render_hash).with_for_update())
    ).scalar_one()
    if row.status == "failed":  # повтор неудачного — только явным запросом
        row.status, row.error, row.created_at, row.finished_at = "pending", None, now, None
    if row.status == "pending":
        renders.queue_after_commit(session, render_hash)
    elif row.status == "ready":
        await _materialize(session, storage, row)
        return CallNote(id=file_id, status="ready", error=None, file=await _ref(session, file_id))
    await session.flush()
    return CallNote(id=file_id, status="pending", error=None, file=None)


async def state(session: AsyncSession, employee: Employee, file_id: uuid.UUID) -> CallNote:
    """Состояние записки автора: готова — файл, строится или не удалась; чужая и неизвестная — 404."""
    stored = await session.get(StoredFile, file_id)
    if stored is not None:
        if stored.created_by != employee.crm_user_id:
            raise not_found("Записка не найдена.")
        return CallNote(id=file_id, status="ready", error=None, file=await _ref(session, file_id))
    found = (
        await session.execute(
            select(DocumentRender)
            .where(DocumentRender.payload["call_note"]["file_id"].as_string() == str(file_id))
            .order_by(DocumentRender.created_at.desc())
            .limit(1)
        )
    ).scalars()
    render = next(iter(found), None)
    if render is None or int(render.payload["call_note"]["owner"]) != employee.crm_user_id:
        raise not_found("Записка не найдена.")
    return CallNote(
        id=file_id, status="failed" if render.status == "failed" else "pending", error=render.error, file=None
    )


