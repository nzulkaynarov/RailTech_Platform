import { useLayoutEffect, useRef } from 'react';

/**
 * Ссылка на ПОСЛЕДНЕЕ значение для стабильных колбэков.
 *
 * Заменяет распространённый в билдере КП самодел `const ref = useRef(v); ref.current = v;` —
 * запись в ref ПРЯМО В РЕНДЕРЕ. Рендер обязан быть чистым: в конкурентном режиме React вправе
 * начать рендер, выбросить его результат и перерисовать заново, — и тогда ref останется с
 * данными выброшенного прохода. Правило `react-hooks/refs` из eslint-plugin-react-hooks 7
 * ловит это как «Ref values may not be read or written during render».
 *
 * Здесь значение записывается в `useLayoutEffect`, то есть ПОСЛЕ коммита и ДО отрисовки:
 * колбэк, вызванный из обработчика события или из обычного эффекта, всегда видит свежее.
 *
 * ГРАНИЦА ПРИМЕНИМОСТИ: читать `.current` можно только ПОСЛЕ коммита — из обработчиков,
 * колбэков и эффектов. Во время рендера там лежит значение предыдущего коммита; если значение
 * нужно в разметке, это не ref, а состояние или обычная переменная.
 *
 * (Канон React 19 для этой задачи — `useEffectEvent`; проект на React 18.3, поэтому
 * «последняя ссылка» остаётся официальным обходным путём.)
 */
export function useLatestRef<T>(value: T): React.MutableRefObject<T> {
  const ref = useRef(value);
  useLayoutEffect(() => {
    ref.current = value;
  }, [value]);
  return ref;
}
