import { apiClient } from './client';

// ─── Document templates («Прочие документы» — library) ────────────
//
// Backend contract (crm/serializers/documents.py DocumentTemplateSerializer). The
// generated schema types these loosely (`placeholders_used: unknown`); we narrow
// them locally so the page + hooks (reused by wave-A3) stay strongly typed.

export interface DocumentTemplate {
  id: number;
  name: string;
  kind: string;
  kind_code: string;
  kind_name: string;
  body_html: string;
  placeholders_used: string[];
  is_sample: boolean;
  is_active: boolean;
  is_owned: boolean;
  created_at: string;
  updated_at: string;
}

export interface CreateTemplatePayload {
  name: string;
  kind: string;
  body_html: string;
}

export interface UpdateTemplatePayload {
  name?: string;
  kind?: string;
  body_html?: string;
  is_active?: boolean;
}

// Live-preview: server renders {{code}} whitelist replacement + returns unknown placeholders as
// warnings (body sanitised server-side). See spec-documents-hub §placeholders.
export interface TemplatePreviewResult {
  rendered_html: string;
  placeholders_used: string[];
  warnings: string[];
}

// Placeholder catalog is static reference data (Bitrix24 insert-chip pattern).
export interface PlaceholderCatalogEntry {
  code: string;
  label: string;
}

// ─── Generated documents (rendered instances) ─────────────────────

export type GeneratedDocumentStatus = 'DRAFT' | 'ISSUED' | 'CANCELLED';

export interface GeneratedDocument {
  id: number;
  number: string;
  title: string;
  status: number;
  status_code: GeneratedDocumentStatus;
  status_name: string;
  template: number;
  template_name: string;
  deal: number | null;
  deal_title: string | null;
  contact: number | null;
  contact_name: string | null;
  values: Record<string, string>;
  rendered_html: string;
  pdf_available: boolean;
  issued_at: string | null;
  created_by_name: string | null;
  created_at: string;
  updated_at: string;
  // ── F2 «Доставка письма» (backend enriches the serializer; schema regenerated by the
  //    orchestrator after F2-1 lands — typed locally so the build is green meanwhile).
  /** True = the document belongs to the viewer's company. False = received from a counterparty
   *  (read-only — no issue/cancel/value editing; badge «Получен»). */
  is_owned: boolean;
  /** Public no-login share URL (backend-built from FRONTEND_URL + token), non-null only for ISSUED. */
  public_url: string | null;
  /** Pre-resolved recipient email (deal contact), when the backend can determine it. Optional —
   *  when absent the send dialog leaves the field empty and the backend resolves it server-side. */
  recipient_email?: string | null;
}

export interface GenerateDocumentPayload {
  template_id: number;
  deal_id?: number;
  contact_id?: number;
  title?: string;
}

// ─── Templates API ────────────────────────────────────────────────
// The template list endpoint sets `pagination_class = None` → a plain array
// (own templates + global platform samples, samples first).

export const documentTemplatesApi = {
  list: async () => {
    const response = await apiClient.get<DocumentTemplate[]>('crm/document-templates/');
    return response.data;
  },
  get: async (id: number) => {
    const response = await apiClient.get<DocumentTemplate>(`crm/document-templates/${id}/`);
    return response.data;
  },
  create: async (payload: CreateTemplatePayload) => {
    const response = await apiClient.post<DocumentTemplate>('crm/document-templates/', payload);
    return response.data;
  },
  update: async (id: number, payload: UpdateTemplatePayload) => {
    const response = await apiClient.patch<DocumentTemplate>(`crm/document-templates/${id}/`, payload);
    return response.data;
  },
  remove: async (id: number) => {
    await apiClient.delete(`crm/document-templates/${id}/`);
  },
  copy: async (id: number) => {
    const response = await apiClient.post<DocumentTemplate>(`crm/document-templates/${id}/copy/`);
    return response.data;
  },
  preview: async (bodyHtml: string) => {
    const response = await apiClient.post<TemplatePreviewResult>('crm/document-templates/preview/', {
      body_html: bodyHtml,
    });
    return response.data;
  },
  placeholders: async () => {
    // Backend wraps the catalogue as { placeholders: [...] } (avoids a top-level JSON array).
    const response = await apiClient.get<{ placeholders: PlaceholderCatalogEntry[] }>(
      'crm/document-templates/placeholders/',
    );
    return response.data.placeholders;
  },
};

// ─── Generated documents API ──────────────────────────────────────
// The generated-documents list is UNPAGINATED (pagination_class = None) → plain array. The registry
// does client-side filter/sort/paging + stat tiles over the full set, so it must receive every row.

export const generatedDocumentsApi = {
  list: async (params?: { status?: string; deal?: number }) => {
    const response = await apiClient.get<GeneratedDocument[]>('crm/generated-documents/', { params });
    return response.data;
  },
  get: async (id: number) => {
    const response = await apiClient.get<GeneratedDocument>(`crm/generated-documents/${id}/`);
    return response.data;
  },
  generate: async (payload: GenerateDocumentPayload) => {
    const response = await apiClient.post<GeneratedDocument>('crm/generated-documents/generate/', payload);
    return response.data;
  },
  updateValues: async (id: number, values: Record<string, string>) => {
    const response = await apiClient.patch<GeneratedDocument>(`crm/generated-documents/${id}/`, { values });
    return response.data;
  },
  issue: async (id: number) => {
    const response = await apiClient.post<GeneratedDocument>(`crm/generated-documents/${id}/issue/`);
    return response.data;
  },
  cancel: async (id: number) => {
    const response = await apiClient.post<GeneratedDocument>(`crm/generated-documents/${id}/cancel/`);
    return response.data;
  },
  // F2 II-1: email an ISSUED document (public link in the body). `to` optional — the backend
  // falls back to the deal contact's email when omitted (NO_RECIPIENT if it cannot resolve one).
  sendEmail: async (id: number, to?: string) => {
    const response = await apiClient.post<GeneratedDocument>(
      `crm/generated-documents/${id}/send-email/`,
      to ? { to } : {},
    );
    return response.data;
  },
};
