from django.apps import AppConfig


class MasterDataConfig(AppConfig):
    default_auto_field = "django.db.models.BigAutoField"
    name = "master_data"

    def ready(self):
        # Сброс кэша справочников висит на ЗАПИСИ МОДЕЛИ, а не на пути записи.
        #
        # До 26-08 версию кэша двигали только хуки вьюсета (`perform_create/update/destroy`),
        # то есть ровно один путь — API. Инженерная админка пишет ту же таблицу напрямую, и
        # правка оттуда до десяти минут не доходила до арендаторов: выпадающие списки отдавали
        # старое имя валюты, а деактивированная строка продолжала предлагаться к выбору.
        # Ровно тот класс «сделал — не видно», из-за которого путь считают мёртвым.
        #
        # Канон тот же, что уже записан в комментарии к самому кэшу: Odoo сбрасывает `ormcache`
        # НА ЗАПИСЬ, Rails строит ключ от `updated_at`. Сигнал ловит любого писателя — вьюсет,
        # админку, management-команду, шелл — и новый путь записи не потребует о нём помнить.
        from . import signals  # noqa: F401  — подписка на post_save/post_delete
