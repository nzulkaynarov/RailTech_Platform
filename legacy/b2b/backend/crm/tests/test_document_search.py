# ── 5. Company-scope: seller finds, competitor and non-member do not ──────────


def test_routed_seller_finds_billing_docs_in_every_context(world, docs):
    for ctx in ("BUYER", "SELLER", None):
        pairs = _pairs(_results(_api(world["seller_user"], ctx).get(URL, {"q": "2026-00042"})))
        for key in ("contract", "invoice", "act"):
            assert (key, docs[key].id) in pairs, f"seller lost {key} ctx={ctx}"


def test_routed_seller_finds_quote_only_in_seller_context(world, docs):
    quote_key = ("quote", docs["quote"].id)
    for ctx in ("SELLER", None):
        found = _pairs(_results(_api(world["seller_user"], ctx).get(URL, {"q": "2026-00042"})))
        assert quote_key in found, f"seller lost quote ctx={ctx}"
    assert quote_key not in _pairs(_results(_api(world["seller_user"], "BUYER").get(URL, {"q": "2026-00042"})))


def test_competitor_seller_finds_none_of_the_deal_documents(world, docs):
    our = {
        ("quote", docs["quote"].id),
        ("contract", docs["contract"].id),
        ("invoice", docs["invoice"].id),
        ("act", docs["act"].id),
        ("generated", docs["generated"].id),
    }
    for ctx in ("BUYER", "SELLER", None):
        pairs = _pairs(_results(_api(world["other_user"], ctx).get(URL, {"q": "2026-00042"})))
        assert pairs.isdisjoint(our), f"competitor matched the deal's documents ctx={ctx}"
    # Searching the shared deal title surfaces ONLY the competitor's own document (its DRAFT
    # letter on the deal), never any of the buyer/seller documents (hidden competition).
    title_pairs = _pairs(_results(_api(world["other_user"]).get(URL, {"q": "мостовой"})))
    assert title_pairs.isdisjoint(our)
    assert title_pairs <= {("generated", docs["foreign_draft"].id)}


def test_foreign_draft_generated_never_matches(world, docs):
    foreign = ("generated", docs["foreign_draft"].id)
    for viewer in ("buyer_user", "seller_user"):
        for query in ("Секрет", "DOC-OTHER", "2026-00042"):
            for ctx in ("BUYER", "SELLER", None):
                pairs = _pairs(_results(_api(world[viewer], ctx).get(URL, {"q": query})))
                assert foreign not in pairs, f"foreign DRAFT letter leaked to {viewer} q={query} ctx={ctx}"


def test_non_member_finds_nothing(world, docs):
    assert _results(_api(world["nonmember_user"]).get(URL, {"q": "2026-00042"})) == []


def test_platform_admin_finds_all_types(world, docs):
    pairs = _pairs(_results(_api(world["admin_user"], "BUYER").get(URL, {"q": "2026-00042"})))
    assert pairs >= {
        ("quote", docs["quote"].id),
        ("contract", docs["contract"].id),
        ("invoice", docs["invoice"].id),
        ("act", docs["act"].id),
        ("generated", docs["generated"].id),
    }
