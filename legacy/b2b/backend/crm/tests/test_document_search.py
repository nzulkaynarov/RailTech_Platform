"""Сквозной поиск по документам — the cross-type global document search feed
(GET /api/v1/crm/analytics/search-documents/?q=<str>).

Covers: textual match by number and by deal title ACROSS types; a type-specific match
(generated by its title); the min-length short-circuit (q<2 → []); the `limit` clamp; the
per-type deep-link hash; and company-scoping — a routed seller / buyer find their deal's
documents, a co-routed competitor does NOT (hidden competition, ADR-0003 §5), another
company's DRAFT сгенерированный документ never surfaces, and a non-member finds nothing.

Self-contained lookup seeding (CI runs --nomigrations). Run with `-p no:randomly`."""

