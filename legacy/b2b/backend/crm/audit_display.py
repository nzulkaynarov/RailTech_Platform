"""Как называть автора события в лентах и журнале доступа.

`get_full_name()` возвращает пустую строку, если у человека не заполнены имя и фамилия — а у
служебных и заведённых оператором аккаунтов они часто пусты. Из-за этого запись с автором
выглядела в журнале ровно как запись БЕЗ автора: пустая ячейка. Ради ответа на вопрос «кто это
сделал» журнал и существует, поэтому подставляем email — как Django admin показывает username, а
Odoo и Stripe откатываются на логин.

Пустая строка остаётся только там, где автора действительно нет (клиент открыл КП по публичной
ссылке, задача просрочила КП) — и это осмысленное «система», а не потерянный человек.
"""


def actor_display_name(activity_log) -> str:
    actor = getattr(activity_log, "user", None)
    if actor is None:
        return ""
    return (actor.get_full_name() or "").strip() or actor.email
