"""Формулировки документов: платформенные значения по умолчанию и их подстановка.

Граница «код / данные» проведена так, как её проводят эталоны отчётов (Odoo QWeb: настраиваемый
текст живёт в полях модели и подставляется в шаблон, в код лезут только за структурными
изменениями; PandaDoc: тело — контент, каркас — системный):

* **каркас остаётся кодом** — таблица позиций, блок итогов, реквизиты сторон, подписи, нумерация.
  Их правка ломает документ и его юридическую полноту, поэтому пользователю она не отдаётся;
* **прозаические формулировки становятся данными** — приёмка, ответственность, особые условия,
  оговорка в акте. У каждой компании они свои: у одной неустойка 0,1%, у другой 0,05%.

Механизм подстановки — тот же, что у сопроводительного текста КП (`resolve_cover_letter`):
ПЛОСКАЯ замена токенов, никакого рендера Django-шаблона (нет SSTI), значения печатаются через
`|linebreaks` и автоэкранируются (нет XSS).

Пустое поле означает «печатать платформенную формулировку», а не «печатать пусто»: компания,
которая ничего не настраивала, получает ровно тот же документ, что и до появления настроек.
"""

#: Приёмка и качество (пункт 4 договора).
DEFAULT_CONTRACT_ACCEPTANCE = (
    "Качество и комплектность товара должны соответствовать действующим стандартам (ГОСТ/ТУ), "
    "технической документации и Спецификации. Приёмка товара по количеству и качеству производится "
    "Покупателем в момент получения; по результатам приёмки Стороны подписывают акт приёма-передачи. "
    "При обнаружении недостатков Покупатель вправе заявить претензию в порядке, установленном "
    "законодательством."
)

#: Ответственность сторон (пункт 5 договора). Ставку неустойки компании меняют чаще всего.
DEFAULT_CONTRACT_LIABILITY = (
    "За нарушение сроков поставки или оплаты виновная Сторона уплачивает неустойку в размере 0,1% от "
    "стоимости просроченного обязательства за каждый день просрочки, но не более 10% от такой "
    "стоимости. Уплата неустойки не освобождает Стороны от исполнения обязательств по Договору."
)

#: Оговорка в акте приёма-передачи.
DEFAULT_ACT_CLOSING = (
    "Услуги / товары оказаны / поставлены в полном объёме и в согласованные сроки. Стороны претензий "
    "по объёму, качеству, комплектности и срокам друг к другу не имеют."
)

#: Особые условия договора печатаются, ТОЛЬКО если компания их написала: пустой пункт в договоре
#: хуже отсутствующего — он выглядит как недооформленный документ.
DEFAULT_CONTRACT_EXTRA_TERMS = ""

#: Поле профиля → платформенное значение. Один словарь, чтобы список настраиваемых формулировок
#: нельзя было расширить в одном месте и забыть в другом.
DOCUMENT_WORDING_DEFAULTS = {
    "contract_acceptance_text": DEFAULT_CONTRACT_ACCEPTANCE,
    "contract_liability_text": DEFAULT_CONTRACT_LIABILITY,
    "contract_extra_terms_text": DEFAULT_CONTRACT_EXTRA_TERMS,
    "act_closing_text": DEFAULT_ACT_CLOSING,
}


def resolve_wording(profile, field: str, **tokens) -> str:
    """Формулировка компании либо платформенная, с плоской подстановкой токенов.

    `tokens` — необязательные значения вида `buyer="ООО Ромашка"`, подставляемые как `{{buyer}}`.
    Текст НИКОГДА не рендерится как шаблон: подстановка строковая, а вывод экранируется вызывающим
    шаблоном.
    """
    from .services.documents.blank import substitute_tokens

    default = DOCUMENT_WORDING_DEFAULTS.get(field, "")
    text = (getattr(profile, field, "") or "").strip() if profile is not None else ""
    return substitute_tokens(text or default, **tokens)


def document_wording_context(profile) -> dict:
    """Готовые формулировки для контекста шаблона.

    Django-шаблон не умеет вызывать функцию с аргументами, поэтому строки резолвятся здесь —
    там же, где собираются остальные блоки документа (`blank.py`). Одно место: и настоящий PDF,
    и предпросмотр в настройках берут текст отсюда и не могут разойтись.
    """
    return {f"wording_{field}": resolve_wording(profile, field) for field in DOCUMENT_WORDING_DEFAULTS}
